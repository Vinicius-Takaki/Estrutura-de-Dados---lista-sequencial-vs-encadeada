"""
Reads results.csv (generated by benchmark_sequential and benchmark_linked)
and produces a comparison chart (comparisons vs. n) for each operation,
saved to ../assets/comparison_chart.png.

Usage:
    python3 plot_results.py
"""

import csv
import os
from collections import defaultdict

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

HERE = os.path.dirname(os.path.abspath(__file__))
CSV_PATH = os.path.join(HERE, "results.csv")
OUTPUT_PATH = os.path.join(HERE, "..", "assets", "comparison_chart.png")

OPERATIONS = [
    "insert_start",
    "insert_middle",
    "insert_end",
    "search_worst",
    "remove_start",
    "remove_middle",
    "remove_end",
]

OP_LABELS = {
    "insert_start": "Insert at start",
    "insert_middle": "Insert in middle",
    "insert_end": "Insert at end",
    "search_worst": "Search (worst case)",
    "remove_start": "Remove from start",
    "remove_middle": "Remove from middle",
    "remove_end": "Remove from end",
}


def load_data():
    # data[structure][operation] = list of (n, comparisons)
    data = defaultdict(lambda: defaultdict(list))
    with open(CSV_PATH) as f:
        reader = csv.DictReader(f)
        for row in reader:
            structure = row["structure"]
            op = row["operation"]
            n = int(row["n"])
            comparisons = int(row["comparisons"])
            data[structure][op].append((n, comparisons))
    for structure in data:
        for op in data[structure]:
            data[structure][op].sort()
    return data


def main():
    data = load_data()

    fig, axes = plt.subplots(2, 4, figsize=(18, 8))
    axes = axes.flatten()

    for idx, op in enumerate(OPERATIONS):
        ax = axes[idx]
        for structure, color, style, width in (
            ("sequential", "#d95f02", "-", 3),
            ("linked", "#1b9e77", "--", 2),
        ):
            points = data[structure][op]
            xs = [p[0] for p in points]
            ys = [p[1] for p in points]
            ax.plot(xs, ys, marker="o", label=structure, color=color,
                     linestyle=style, linewidth=width)
        ax.set_title(OP_LABELS[op])
        ax.set_xlabel("n (list size)")
        ax.set_ylabel("Comparisons")
        ax.legend()
        ax.grid(True, alpha=0.3)

    # hide unused subplot (8 slots, 7 operations)
    for idx in range(len(OPERATIONS), len(axes)):
        axes[idx].axis("off")

    fig.suptitle(
        "Sequential List vs Linked List — Comparisons per Operation",
        fontsize=16,
    )
    fig.tight_layout(rect=[0, 0, 1, 0.96])

    os.makedirs(os.path.dirname(OUTPUT_PATH), exist_ok=True)
    fig.savefig(OUTPUT_PATH, dpi=150)
    print(f"Chart saved to {OUTPUT_PATH}")


if __name__ == "__main__":
    main()
